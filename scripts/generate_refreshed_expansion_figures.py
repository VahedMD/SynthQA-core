"""Regenerate the expansion-arm figures from the frozen refreshed n=30 CSV.

This script intentionally does not download data, select patients, or rerun dose calculations.
It updates Fig4 and Fig11 only; other figure panels are generated by their original analysis
scripts and must be regenerated from their corresponding case-level outputs.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


def bootstrap_ci(x, y, n_boot=20_000, seed=42):
    x=np.asarray(x,float); y=np.asarray(y,float); n=len(x)
    rng=np.random.RandomState(seed)
    maes=np.empty(n_boot); biases=np.empty(n_boot); rs=np.empty(n_boot)
    for b in range(n_boot):
        ix=rng.randint(0,n,n); d=x[ix]-y[ix]
        maes[b]=np.mean(np.abs(d)); biases[b]=np.mean(d)
        rs[b]=np.corrcoef(x[ix],y[ix])[0,1] if np.std(x[ix])>0 and np.std(y[ix])>0 else np.nan
    d=x-y
    return {
      'mae':float(np.mean(np.abs(d))), 'bias':float(np.mean(d)),
      'rmse':float(np.sqrt(np.mean(d*d))), 'r':float(np.corrcoef(x,y)[0,1]),
      'mae_ci':np.nanpercentile(maes,[2.5,97.5]).tolist(),
      'bias_ci':np.nanpercentile(biases,[2.5,97.5]).tolist(),
      'r_ci':np.nanpercentile(rs,[2.5,97.5]).tolist(),
    }


def load_cohort(path: Path):
    df=pd.read_csv(path)
    required={'Patient','Pred_mm','Act_mm','Region','Metal'}
    missing=required-set(df.columns)
    if missing: raise ValueError(f'Missing columns: {sorted(missing)}')
    if len(df)!=30 or df.Patient.astype(str).nunique()!=30:
        raise ValueError(f'Expected 30 unique patients; found {len(df)} rows / {df.Patient.nunique()} IDs')
    ids=set(df.Patient.astype(str))
    if '1THB121' in ids: raise ValueError('Outlier 1THB121 must remain excluded.')
    if '1ABB143' not in ids: raise ValueError('Replacement patient 1ABB143 not found.')
    if not np.isfinite(df[['Pred_mm','Act_mm']].to_numpy(float)).all():
        raise ValueError('Non-finite paired shift values found.')
    return df


def style(ax):
    ax.grid(True, linestyle='--', alpha=.28)
    ax.axhline(0,color='0.5',lw=.7)
    ax.axvline(0,color='0.5',lw=.7)


def fig4(df, out):
    x=df.Pred_mm.to_numpy(float); y=df.Act_mm.to_numpy(float)
    st=bootstrap_ci(x,y)
    lo=min(x.min(),y.min())-.5; hi=max(x.max(),y.max())+.5
    fig,ax=plt.subplots(figsize=(7.2,6.4))
    for region,marker in [('Thorax','o'),('Abdomen','s')]:
        q=df.Region.astype(str).eq(region)
        ax.scatter(x[q],y[q],s=48,marker=marker,alpha=.82,edgecolor='black',linewidth=.45,label=f'{region} (n={q.sum()})')
    ax.plot([lo,hi],[lo,hi],'k--',lw=1.3,label='Identity')
    ax.set(xlim=(lo,hi),ylim=(lo,hi),xlabel='Surrogate-predicted range shift (mm)',ylabel='Analytically reconstructed reference shift (mm)',title='Global +50 HU perturbation: refreshed expansion cohort')
    ax.text(.03,.97,f"n = 30\nMAE = {st['mae']:.3f} mm\nBias = {st['bias']:.3f} mm\nPearson r = {st['r']:.3f}",transform=ax.transAxes,va='top',ha='left',bbox=dict(boxstyle='round,pad=.35',fc='white',ec='0.75',alpha=.9))
    ax.legend(frameon=True,loc='lower right'); style(ax); fig.tight_layout()
    fig.savefig(out/'Fig4_ModelA_Expansion_Refreshed.png',dpi=300,bbox_inches='tight'); fig.savefig(out/'Fig4_ModelA_Expansion_Refreshed.pdf',bbox_inches='tight'); plt.close(fig)
    return st


def fig11(df,out):
    x=df.Pred_mm.to_numpy(float); y=df.Act_mm.to_numpy(float); st=bootstrap_ci(x,y)
    diff=x-y; mean=(x+y)/2; bias=diff.mean(); sd=diff.std(ddof=1)
    fig,axes=plt.subplots(1,2,figsize=(12.2,5.2))
    ax=axes[0]; lo=min(x.min(),y.min())-.5; hi=max(x.max(),y.max())+.5
    ax.scatter(x,y,c=np.where(df.Metal.astype(bool),'tab:orange','tab:blue'),s=46,edgecolor='black',linewidth=.35,alpha=.85)
    ax.plot([lo,hi],[lo,hi],'k--',lw=1.2)
    ax.set(xlim=(lo,hi),ylim=(lo,hi),xlabel='Surrogate-predicted shift (mm)',ylabel='Analytically reconstructed shift (mm)',title='(a) Paired range-shift agreement')
    ax.text(.03,.97,f"MAE {st['mae']:.3f} mm\nBias {st['bias']:.3f} mm\nr {st['r']:.3f}",transform=ax.transAxes,va='top',bbox=dict(fc='white',ec='.8',alpha=.9))
    ax.legend(handles=[plt.Line2D([],[],marker='o',linestyle='',color='tab:blue',label='Non-metal'),plt.Line2D([],[],marker='o',linestyle='',color='tab:orange',label='Metal')],loc='lower right')
    style(ax)
    ax=axes[1]; ax.scatter(mean,diff,c='0.25',s=42,alpha=.8,edgecolor='white',linewidth=.35)
    ax.axhline(bias,color='tab:red',label=f'Bias {bias:.3f} mm')
    ax.axhline(bias+1.96*sd,color='tab:gray',ls='--',label=f'+1.96 SD {bias+1.96*sd:.3f}')
    ax.axhline(bias-1.96*sd,color='tab:gray',ls='--',label=f'−1.96 SD {bias-1.96*sd:.3f}')
    ax.set(xlabel='Mean of paired shifts (mm)',ylabel='Prediction − reference (mm)',title='(b) Difference versus mean'); ax.grid(True,ls='--',alpha=.28); ax.legend(fontsize=8)
    fig.suptitle('Refreshed 30-patient expansion cohort — analytical reference',y=1.02)
    fig.tight_layout(); fig.savefig(out/'Fig11_Expansion_Agreement_BlandAltman.png',dpi=300,bbox_inches='tight'); fig.savefig(out/'Fig11_Expansion_Agreement_BlandAltman.pdf',bbox_inches='tight'); plt.close(fig)
    return st


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--csv',default='outputs/reproducibility/refresh_excl_1THB121/model_a_expansion_case_level_n30.csv')
    ap.add_argument('--out-dir',default='figures')
    args=ap.parse_args(); path=Path(args.csv); out=Path(args.out_dir); out.mkdir(parents=True,exist_ok=True)
    df=load_cohort(path)
    s4=fig4(df,out); s11=fig11(df,out)
    import json
    (out/'refreshed_expansion_figure_statistics.json').write_text(json.dumps({'source_csv':str(path),'n':len(df),'excluded_patient':'1THB121','replacement_patient':'1ABB143','Fig4':s4,'Fig11':s11},indent=2),encoding='utf-8')
    print(f'Loaded frozen cohort: {path} (n={len(df)})')
    print(f"MAE={s4['mae']:.6f} mm; bias={s4['bias']:.6f} mm; RMSE={s4['rmse']:.6f} mm; r={s4['r']:.6f}")
    print('Updated Fig4 and Fig11. No patient selection or dose recalculation was performed.')

if __name__=='__main__': main()
